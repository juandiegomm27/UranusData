-- V2 · COMPLEMENTARIAS: soporte, historiales y preferencias

CREATE TABLE password_reset_tokens (
    documento  VARCHAR(20) PRIMARY KEY
        REFERENCES usuario (documento) ON UPDATE CASCADE ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Ajustes del usuario
CREATE TABLE preferencias_usuario (
    documento            VARCHAR(20) PRIMARY KEY
        REFERENCES usuario (documento) ON UPDATE CASCADE ON DELETE CASCADE,
    tema_oscuro          BOOLEAN     NOT NULL DEFAULT FALSE,
    notificaciones_email BOOLEAN     NOT NULL DEFAULT TRUE,
    notificaciones_push  BOOLEAN     NOT NULL DEFAULT TRUE,
    idioma               VARCHAR(5)  NOT NULL DEFAULT 'es'
);

-- Notificaciones internas
CREATE TABLE notificaciones (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento       VARCHAR(20)  NOT NULL
        REFERENCES usuario (documento) ON UPDATE CASCADE ON DELETE CASCADE,
    titulo          VARCHAR(150) NOT NULL,
    mensaje         TEXT         NOT NULL,
    tipo            VARCHAR(20)  NOT NULL DEFAULT 'info',
    leida           BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_creacion  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_notif_documento ON notificaciones (documento, fecha_creacion DESC);

-- Historial de bajas (instantánea: sin llaves foráneas, a propósito)
CREATE TABLE historial_bajas_general (
    id_baja               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_item             VARCHAR(10)  NOT NULL CHECK (tipo_item IN ('activo', 'accesorio')),
    id_original           INTEGER      NOT NULL,
    id_accesorio          INTEGER,
    nombre                VARCHAR(100) NOT NULL,
    codigo_identificacion VARCHAR(100),
    modelo                VARCHAR(100),
    descripcion           TEXT,
    cantidad              INTEGER      NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    cod_tipo_elemento     INTEGER,
    cod_ubi_elemento      INTEGER,
    ubicacion             VARCHAR(100),
    motivo                VARCHAR(255),
    fecha_baja            TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_bajas_tipo ON historial_bajas_general (tipo_item, fecha_baja DESC);

-- Movimientos (alta, edición, traslado, vínculo, baja, restauración)
CREATE TABLE inventario_movimientos (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_elemento   INTEGER      NOT NULL REFERENCES inventario (id_elemento),
    tipo          VARCHAR(30)  NOT NULL,
    descripcion   TEXT         NOT NULL,
    datos         JSONB,
    documento     VARCHAR(20),
    usuario       VARCHAR(100),
    fecha         TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_mov_elemento ON inventario_movimientos (id_elemento, id_movimiento DESC);