-- ---------- USUARIOS ----------
CREATE TABLE rol (
    cod_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cargo   VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE estado_usuario (
    cod_estado_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado             VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE usuario (
    documento          VARCHAR(20)  PRIMARY KEY,
    nombre             VARCHAR(45)  NOT NULL,
    apellido           VARCHAR(45)  NOT NULL,
    cod_rol            INTEGER      NOT NULL REFERENCES rol (cod_rol),
    cod_estado_usuario INTEGER      NOT NULL DEFAULT 2 REFERENCES estado_usuario (cod_estado_usuario),
    password           VARCHAR(255) NOT NULL
);
CREATE INDEX idx_usuario_rol    ON usuario (cod_rol);
CREATE INDEX idx_usuario_estado ON usuario (cod_estado_usuario);

CREATE TABLE correo (
    correo    VARCHAR(100) PRIMARY KEY,
    documento VARCHAR(20)  NOT NULL
        REFERENCES usuario (documento) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_correo_documento ON correo (documento);

CREATE TABLE telefono (
    telefono  VARCHAR(20) PRIMARY KEY,
    documento VARCHAR(20) NOT NULL
        REFERENCES usuario (documento) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_telefono_documento ON telefono (documento);

-- ---------- CATÁLOGOS DE INVENTARIO ----------
CREATE TABLE estado_elemento (
    cod_estado_elemento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado              VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE tipo_elemento (
    cod_tipo_elemento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo              VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE ubi_elemento (
    cod_ubi_elemento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ubicacion        VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE marca (
    cod_marca INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca     VARCHAR(100) NOT NULL UNIQUE
);

-- ---------- INVENTARIO (activos con serial) ----------
CREATE TABLE inventario (
    id_elemento         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_elemento        VARCHAR(45)  UNIQUE,
    nombre_elemento     VARCHAR(100) NOT NULL,
    serial              VARCHAR(100) UNIQUE,
    modelo              VARCHAR(100),
    descripcion         TEXT,
    cod_tipo_elemento   INTEGER NOT NULL REFERENCES tipo_elemento (cod_tipo_elemento),
    cod_marca           INTEGER REFERENCES marca (cod_marca),
    cod_estado_elemento INTEGER NOT NULL DEFAULT 1 REFERENCES estado_elemento (cod_estado_elemento),
    cod_ubi_elemento    INTEGER NOT NULL REFERENCES ubi_elemento (cod_ubi_elemento),
    id_elemento_padre   INTEGER REFERENCES inventario (id_elemento) ON DELETE SET NULL,
    CONSTRAINT ck_inventario_padre CHECK (id_elemento_padre IS NULL OR id_elemento_padre <> id_elemento)
);
CREATE INDEX idx_inventario_tipo   ON inventario (cod_tipo_elemento);
CREATE INDEX idx_inventario_marca  ON inventario (cod_marca);
CREATE INDEX idx_inventario_estado ON inventario (cod_estado_elemento);
CREATE INDEX idx_inventario_ubi    ON inventario (cod_ubi_elemento);
CREATE INDEX idx_inventario_padre  ON inventario (id_elemento_padre);

-- ---------- ACCESORIOS (por cantidad) ----------
CREATE TABLE inventario_accesorios (
    id_accesorio        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(100) NOT NULL,
    modelo              VARCHAR(100),
    descripcion         TEXT,
    cod_tipo_elemento   INTEGER REFERENCES tipo_elemento (cod_tipo_elemento),
    cod_marca           INTEGER REFERENCES marca (cod_marca),
    cantidad_total      INTEGER NOT NULL DEFAULT 0,
    cantidad_disponible INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_accesorio_cantidades CHECK (
        cantidad_total >= 0 AND cantidad_disponible >= 0 AND cantidad_disponible <= cantidad_total)
);
CREATE UNIQUE INDEX uq_accesorio_nombre ON inventario_accesorios (lower(btrim(nombre)));
CREATE INDEX idx_accesorio_tipo  ON inventario_accesorios (cod_tipo_elemento);
CREATE INDEX idx_accesorio_marca ON inventario_accesorios (cod_marca);

CREATE TABLE stock_accesorios (
    id_stock            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_accesorio        INTEGER NOT NULL REFERENCES inventario_accesorios (id_accesorio) ON DELETE CASCADE,
    cod_ubi_elemento    INTEGER NOT NULL REFERENCES ubi_elemento (cod_ubi_elemento),
    cantidad_total      INTEGER NOT NULL DEFAULT 0,
    cantidad_disponible INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_stock_accesorio_ubicacion UNIQUE (id_accesorio, cod_ubi_elemento),
    CONSTRAINT ck_stock_cantidades CHECK (
        cantidad_total >= 0 AND cantidad_disponible >= 0 AND cantidad_disponible <= cantidad_total)
);
CREATE INDEX idx_stock_ubi ON stock_accesorios (cod_ubi_elemento);

-- ---------- MANTENIMIENTO ----------
CREATE TABLE tipo_mantenimiento (
    cod_tipo_mantenimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                   VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE estado_mantenimiento (
    cod_estado_mantenimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado                   VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE mantenimiento (
    id_mantenimiento         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha                    DATE    NOT NULL,
    cod_tipo_mantenimiento   INTEGER NOT NULL REFERENCES tipo_mantenimiento (cod_tipo_mantenimiento),
    documento                VARCHAR(20) NOT NULL REFERENCES usuario (documento) ON UPDATE CASCADE,
    id_elemento              INTEGER NOT NULL REFERENCES inventario (id_elemento),
    elemento                 VARCHAR(100),
    serial                   VARCHAR(100),
    descripcion              TEXT,
    observaciones            TEXT,
    cod_estado_mantenimiento INTEGER NOT NULL DEFAULT 1 REFERENCES estado_mantenimiento (cod_estado_mantenimiento)
);
CREATE INDEX idx_mant_elemento  ON mantenimiento (id_elemento);
CREATE INDEX idx_mant_documento ON mantenimiento (documento);
CREATE INDEX idx_mant_estado    ON mantenimiento (cod_estado_mantenimiento);
CREATE INDEX idx_mant_tipo      ON mantenimiento (cod_tipo_mantenimiento);
CREATE INDEX idx_mant_fecha     ON mantenimiento (fecha DESC);

-- ---------- RESERVAS Y PRÉSTAMOS ----------
CREATE TABLE estado_reserva (
    num_estado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado     VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE estado_prestamo (
    cod_estado_prestamo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado              VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE reserva (
    id_reserva INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_estado INTEGER NOT NULL REFERENCES estado_reserva (num_estado),
    documento  VARCHAR(20) NOT NULL REFERENCES usuario (documento) ON UPDATE CASCADE,
    fecha      DATE NOT NULL,
    plazo      DATE,
    CONSTRAINT ck_reserva_plazo CHECK (plazo IS NULL OR plazo >= fecha)
);
CREATE INDEX idx_reserva_estado    ON reserva (num_estado);
CREATE INDEX idx_reserva_documento ON reserva (documento);

-- Detalle de cada reserva y cantidades solicitada / entregada / devuelta
CREATE TABLE reserva_detalles (
    id_detalle          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva          INTEGER NOT NULL REFERENCES reserva (id_reserva) ON DELETE CASCADE,
    id_elemento         INTEGER REFERENCES inventario (id_elemento),
    id_stock            INTEGER REFERENCES stock_accesorios (id_stock),
    cantidad_solicitada INTEGER NOT NULL DEFAULT 1,
    cantidad_entregada  INTEGER NOT NULL DEFAULT 0,
    cantidad_devuelta   INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_detalle_origen CHECK (num_nonnulls(id_elemento, id_stock) = 1),
    CONSTRAINT ck_detalle_cantidades CHECK (
        cantidad_solicitada > 0
        AND cantidad_entregada >= 0 AND cantidad_entregada <= cantidad_solicitada
        AND cantidad_devuelta  >= 0 AND cantidad_devuelta  <= cantidad_entregada)
);
CREATE INDEX idx_detalle_reserva  ON reserva_detalles (id_reserva);
CREATE INDEX idx_detalle_elemento ON reserva_detalles (id_elemento);
CREATE INDEX idx_detalle_stock    ON reserva_detalles (id_stock);

CREATE TABLE prestamo (
    id_reserva             INTEGER PRIMARY KEY REFERENCES reserva (id_reserva) ON DELETE CASCADE,
    cod_estado_prestamo    INTEGER NOT NULL REFERENCES estado_prestamo (cod_estado_prestamo),
    fecha_inicio           DATE,
    fecha_entrega_original DATE,
    fecha_limite_actual    DATE,
    extension_aprobada     BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_prestamo_estado ON prestamo (cod_estado_prestamo);